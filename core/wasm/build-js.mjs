#!/usr/bin/env node
/* Builds build/uztranslit.engine.js: the same engine as build/uztranslit.wasm, translated to plain JavaScript
 * by binaryen's wasm2js, for browsers that run without WebAssembly (iOS Lockdown Mode, hardened Edge …).
 * It exports the same functions and a `memory` object with a `buffer` getter, so uztranslit-wasm.mjs
 * drives it unchanged:  new UzTranslitWasm({ exports: await import('./build/uztranslit.engine.js') }) */
import { readFileSync, writeFileSync } from 'node:fs';
import asc from 'assemblyscript/asc';
import binaryen from 'binaryen';

const dir = new URL('.', import.meta.url);
const mvp = new URL('build/uztranslit.mvp.wasm', dir);
// wasm2js cannot translate bulk-memory instructions; AssemblyScript then emits plain loops instead
const { error, stderr } = await asc.main(['assembly/index.ts', '--target', 'release', '--disable', 'bulk-memory',
  '--outFile', 'build/uztranslit.mvp.wasm'], { stdout: process.stdout, stderr: process.stderr });
if (error) { console.error(stderr.toString()); process.exit(1); }

const module = binaryen.readBinary(readFileSync(mvp));
module.setFeatures(binaryen.Features.MVP | binaryen.Features.MutableGlobals | binaryen.Features.SignExt |
  binaryen.Features.NontrappingFPToInt);
if (!module.validate()) { console.error('wasm2js: module does not validate as MVP'); process.exit(1); }
let js = module.emitAsmjs();
const envImport = "import * as env from 'env';";
if (!js.includes(envImport)) { console.error('wasm2js: unexpected import header'); process.exit(1); }
js = js.replace(envImport, "const env = { abort() { throw new Error('uztranslit-engine: aborted'); } };");
writeFileSync(new URL('build/uztranslit.engine.js', dir),
  '/* Generated by core/wasm/build-js.mjs from assembly/index.ts (AssemblyScript → wasm → wasm2js). Do not edit. */\n' + js);
console.log('wrote build/uztranslit.engine.js', js.length, 'bytes');
