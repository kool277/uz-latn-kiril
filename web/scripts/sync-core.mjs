#!/usr/bin/env node
/* Copies what the web app ships or tests against from the rest of the repository (never edit the copies):
 *   core/wasm build    → public/wasm/uztranslit.<hash>.wasm, src/generated/uztranslit-{wasm,engine}.js (+ .d.ts)
 *   spec/fixtures.json → test/generated/fixtures.json (read by the web fixture runner)
 *   office-vba/*.bas, libreoffice/*.oxt  → public/downloads/
 *   platforms/office-addin (task pane)   → public/office/ (the Office add-in is served from /office/)
 *   $UZT_RELEASE_JSON (deploy-pages.yml: `gh release view --json tagName,assets` of the latest release)
 *                      → src/generated/release.ts (the download buttons; null without it, e.g. local builds)
 * core/wasm is (re)built first when its output is missing or older than its sources. */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(web, '..');
const core = join(root, 'core', 'wasm');
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';

const mtime = p => (existsSync(p) ? statSync(p).mtimeMs : 0);
const outputs = ['build/uztranslit.wasm', 'build/uztranslit.engine.js'].map(p => join(core, p));
const sources = ['assembly/index.ts', 'build-js.mjs', 'asconfig.json', 'package-lock.json'].map(p => join(core, p));
if (Math.min(...outputs.map(mtime)) < Math.max(...sources.map(mtime))) {
  console.log('sync-core: building core/wasm');
  if (!existsSync(join(core, 'node_modules', '.bin', 'asc'))) execFileSync(npm, ['ci', '--no-audit', '--no-fund'], { cwd: core, stdio: 'inherit', shell: process.platform === 'win32' });
  execFileSync(npm, ['run', 'build'], { cwd: core, stdio: 'inherit', shell: process.platform === 'win32' });
}

const fresh = dir => { rmSync(dir, { recursive: true, force: true }); mkdirSync(dir, { recursive: true }); };
const generated = join(web, 'src', 'generated');
const wasmDir = join(web, 'public', 'wasm');
fresh(generated);
fresh(wasmDir);

const wasm = readFileSync(outputs[0]);
const hash = createHash('sha256').update(wasm).digest('hex').slice(0, 12);
writeFileSync(join(wasmDir, `uztranslit.${hash}.wasm`), wasm);
copyFileSync(join(core, 'uztranslit-wasm.mjs'), join(generated, 'uztranslit-wasm.js'));
copyFileSync(join(core, 'uztranslit-wasm.d.ts'), join(generated, 'uztranslit-wasm.d.ts'));
copyFileSync(outputs[1], join(generated, 'uztranslit-engine.js'));
writeFileSync(join(generated, 'uztranslit-engine.d.ts'),
  '// exports of core/wasm/build/uztranslit.engine.js (wasm2js); drive them with fromExports()\n' +
  'export declare const memory: { readonly buffer: ArrayBuffer };\n' +
  'export declare function inputBuffer(n: number): number;\nexport declare function boundaryBuffer(n: number): number;\n' +
  'export declare function outputPtr(): number;\nexport declare function resolvedSource(): number;\n' +
  'export declare function detectInput(n: number): number;\n' +
  'export declare function convert(n: number, from: number, to: number, options: number, okina: number, tutuq: number, boundaries: number): number;\n');
writeFileSync(join(generated, 'engine-assets.ts'),
  `// generated by scripts/sync-core.mjs\nexport const WASM_URL = 'wasm/uztranslit.${hash}.wasm';\n`);

const testGenerated = join(web, 'test', 'generated');
fresh(testGenerated);
copyFileSync(join(root, 'spec', 'fixtures.json'), join(testGenerated, 'fixtures.json'));

const downloads = join(web, 'public', 'downloads');
fresh(downloads);
for (const f of ['UzTranslit.bas', 'UzTranslitRibbon.bas']) copyFileSync(join(root, 'office-vba', f), join(downloads, f));
for (const f of readdirSync(join(root, 'libreoffice')).filter(f => f.endsWith('.oxt'))) copyFileSync(join(root, 'libreoffice', f), join(downloads, f));

execFileSync(process.execPath, [join(root, 'platforms', 'office-addin', 'build.mjs'), '--stage', join(web, 'public', 'office')], { stdio: 'ignore' });
for (const f of ['manifest.xml', 'manifest-github-pages.xml']) {
  copyFileSync(join(root, 'platforms', 'office-addin', f), join(downloads, f === 'manifest.xml' ? 'uztranslit-office-addin.xml' : 'uztranslit-office-addin-github-pages.xml'));
}

let release = null;
const releaseJson = process.env.UZT_RELEASE_JSON;
if (releaseJson && existsSync(releaseJson) && statSync(releaseJson).size > 0) {
  const r = JSON.parse(readFileSync(releaseJson, 'utf8'));
  if (!/^v\d+\.\d+\.\d+$/.test(r.tagName ?? '')) throw new Error(`sync-core: unexpected release tag ${r.tagName}`);
  release = { tag: r.tagName, files: (r.assets ?? []).map(a => ({ name: a.name, size: a.size })) };
}
writeFileSync(join(generated, 'release.ts'),
  '// generated by scripts/sync-core.mjs: the latest published release (deploy-pages.yml), null in local builds\n' +
  "import type { ReleaseInfo } from '../app/components/release-info';\n" +
  `export const RELEASE: ReleaseInfo | null = ${JSON.stringify(release, null, 2)};\n`);

console.log(`sync-core: engine ${hash}, fixtures, ${readdirSync(downloads).length} downloads, office add-in, release ${release ? release.tag : 'none'}`);
